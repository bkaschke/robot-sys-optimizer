SPEC = """# {title} registry entry. Generated by scripts/import_cobots.py ({source}).
name: {name}
urdf: {name}.urdf
base_link: base_link
flange_link: {flange}                 # z out of the flange
ik: offset_wrist                     # offset wrist, up to 16 solutions (core.ik.offset_wrist)
reach_m: {reach}                     # data sheet
frame_convention: {conv}
home_deg: {home}                     # arm pose while the carrier moves between stops (wrist down)
"""


def fanuc(src: Path, name: str, macro: str, title: str, reach: float) -> None:
    import xacro  # pip package; only needed for this one-time import

    pkg = src / "fanuc_description" / "fanuc_crx_description"
    out = OUT / name
    if out.exists():
        shutil.rmtree(out)
    (out / "meshes").mkdir(parents=True)
    wrapper = f"""<?xml version="1.0"?>
<robot name="{name}" xmlns:xacro="http://wiki.ros.org/xacro">
  <xacro:include filename="{(pkg / "urdf" / f"{macro}_urdf_macro.xacro").as_posix()}"/>
  <link name="base"/>
  <link name="tip"/>
  <xacro:{macro} parent="base" child="tip"><origin xyz="0 0 0" rpy="0 0 0"/></xacro:{macro}>
</robot>
"""
    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "w.urdf.xacro"
        f.write_text(wrapper, encoding="utf-8")
        urdf = xacro.process_file(str(f)).toprettyxml(indent="  ")
    urdf, n = re.subn(
        r'filename="package://fanuc_crx_description/meshes/' + re.escape(macro) + r'/([^"]+)"',
        r'filename="meshes/\1"',
        urdf,
    )
    if n == 0 or "package://" in urdf:
        sys.exit(f"{name}: unexpected mesh paths")
    (out / f"{name}.urdf").write_text(urdf, encoding="utf-8")
    shutil.copytree(pkg / "meshes" / macro, out / "meshes", dirs_exist_ok=True)
    shutil.copy(
        src / "fanuc_description" / "LICENSES" / "Apache-2.0.txt",
        out / "LICENSE_fanuc_description_Apache-2.0.txt",
    )
    spec = SPEC.format(
        title=title,
        source="FANUC-CORPORATION/fanuc_description, Apache-2.0",
        name=name,
        flange="fanuc_flange",
        reach=reach,
        conv="fanuc                 # userframe export: X Y Z W P R",
        home="[0, 0, 0, 0, -90, 0]",
    )
    (out / "spec.yaml").write_text(spec, encoding="utf-8")


def _link(name: str, mesh: str | None, xyz) -> str:
    if mesh is None:
        return f'  <link name="{name}"/>\n'
    o = " ".join(f"{-v:.6g}" for v in xyz)
    geo = f'<geometry><mesh filename="meshes/{mesh}.stl" scale="0.001 0.001 0.001"/></geometry>'
    return (
        f'  <link name="{name}">\n'
        f'    <visual><origin xyz="{o}" rpy="0 0 0"/>{geo}</visual>\n'
        f'    <collision><origin xyz="{o}" rpy="0 0 0"/>{geo}</collision>\n'
        "  </link>\n"
    )


def abb(src: Path, name: str, d: dict) -> None:
    out = OUT / name
    if out.exists():
        shutil.rmtree(out)
    (out / "meshes").mkdir(parents=True)
    P = [np.zeros(3)] + [np.array(j, float) for j in d["joints"]]
    meshes = d["meshes"]
    s = f'<?xml version="1.0"?>\n<!-- {d["title"]}: generated by scripts/import_cobots.py -->\n'
    s += f'<robot name="{name}">\n'
    s += _link("base_link", meshes[0], P[0])
    for i in range(1, 7):
        s += _link(f"link_{i}", meshes[i], P[i])
        lo, hi = np.radians(d["limits"][i - 1])
        rel = " ".join(f"{v:.6g}" for v in P[i] - P[i - 1])
        vel = np.radians(d["speed"][i - 1])
        s += (
            f'  <joint name="joint_{i}" type="revolute">\n'
            f'    <parent link="{"base_link" if i == 1 else f"link_{i - 1}"}"/><child link="link_{i}"/>\n'
            f'    <origin xyz="{rel}" rpy="0 0 0"/><axis xyz="{ABB_AXES[i - 1]}"/>\n'
            f'    <limit lower="{lo:.6f}" upper="{hi:.6f}" effort="100" velocity="{vel:.4f}"/>\n'
            "  </joint>\n"
        )
    s += _link("flange", None, None) + _link("tool0", None, None)
    rel = " ".join(f"{v:.6g}" for v in np.array(d["flange"], float) - P[6])
    s += (
        f'  <joint name="joint_6-flange" type="fixed"><parent link="link_6"/><child link="flange"/>'
        f'<origin xyz="{rel}" rpy="0 0 0"/></joint>\n'
        '  <joint name="flange-tool0" type="fixed"><parent link="flange"/><child link="tool0"/>'
        '<origin xyz="0 0 0" rpy="0 1.5707963267948966 0"/></joint>\n'
        "</robot>\n"
    )
    (out / f"{name}.urdf").write_text(s, encoding="utf-8")
    for m in meshes:
        shutil.copy(src / "workr" / d["src"] / f"{m}.stl", out / "meshes" / f"{m}.stl")
    lic = src / "workr" / "LICENSE"
    shutil.copy(lic, out / "LICENSE_work-r-labs_robots_MIT.txt")
    spec = SPEC.format(
        title=d["title"],
        source="meshes: work-r-labs/robots, MIT; kinematics: see the script",
        name=name,
        flange="tool0",
        reach=d["reach"],
        conv="matrix",
        home="[0, 0, 0, 0, 90, 0]",
    )
    (out / "spec.yaml").write_text(spec, encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path, help="folder with the fanuc_description and workr clones")
    args = ap.parse_args()
    for name, (macro, title, reach) in FANUC.items():
        fanuc(args.src.resolve(), name, macro, title, reach)
        print("imported", name)
    for name, d in ABB.items():
        abb(args.src.resolve(), name, d)
        print("imported", name)


if __name__ == "__main__":
    main()
