"""One-time import of the FANUC CRX and ABB GoFa / PoWa cobots into assets/robots/.

    git clone --depth 1 https://github.com/FANUC-CORPORATION/fanuc_description.git <src>/fanuc_description
    git clone --depth 1 https://github.com/work-r-labs/robots.git <src>/workr
    python scripts/import_cobots.py <src>

FANUC CRX-10iA, CRX-20iA/L, CRX-30iA: FANUC's own description package (Apache-2.0): the
xacro macro is expanded as is, meshes are copied.

ABB GoFa 10 (CRB 15000-10/1.52), GoFa 12 (CRB 15000-12/1.27), PoWa 30 (CRB 1920-30/1.35): the
meshes come from the work-r-labs robot library (MIT; CAD exports in world coordinates at the
zero pose, mm). The URDF is written here with clean kinematics: joint positions from that
export rounded to 0.1 mm (GoFa 12 agrees with ROS-Industrial's abb_crb15000_support, ABB's
own numbers), 1 mm CAD noise snapped so the J4 and J5 axes intersect (PoWa), the flange at
the end of the link 6 mesh, ABB axis directions (J1 z, J2 y, J3 y, J4 x, J5 y, J6 x) and the
working ranges / axis speeds of ABB's data sheets.

All six use the offset-wrist IK (core.ik.offset_wrist). The folders are committed; this only
reruns when updating a model. Check each with scripts/check_robot.py <name>.
"""

