"""Write ``assets/robots/generic_6r/``: a made-up industrial 6-axis arm (spherical wrist,
OPW kinematics) built from boxes and cylinders. It is not a real product: it exists so the
tool can be tried and tested with a non-UR robot (``ik: opw``), and as a template for adding
a real arm (see docs/USER_GUIDE.md, "Adding a robot").

    python scripts/make_generic_robot.py

The URDF is generated from the same OPW parameters that go into spec.yaml, with KUKA-style
joint offsets and sign flips so those code paths are exercised:
    joint i: origin rotated by -offset_i about its axis, axis = sign_i * (z | y)
which gives theta_i = q_i * sign_i - offset_i (core.ik.opw).
"""

from __future__ import annotations

import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
NAME = "generic_6r"
OPW = dict(a1=0.15, a2=-0.12, b=0.0, c1=0.45, c2=0.60, c3=0.64, c4=0.13)
OFFSETS = (0.0, -math.pi / 2, 0.0, 0.0, 0.0, 0.0)
SIGNS = (-1, 1, 1, -1, 1, -1)
LIMITS_DEG = ((-180, 180), (-150, 150), (-150, 150), (-350, 350), (-125, 125), (-350, 350))
AXES = ("z", "y", "y", "z", "y", "z")
GREY, ORANGE = "0.35 0.37 0.40 1", "0.95 0.55 0.15 1"


def _shape(geo: str, xyz=(0, 0, 0), rpy=(0, 0, 0), color=ORANGE) -> str:
    o = f'<origin xyz="{" ".join(f"{v:.6g}" for v in xyz)}" rpy="{" ".join(f"{v:.6g}" for v in rpy)}"/>'
    return (
        f'<visual>{o}<geometry>{geo}</geometry><material name="c{abs(hash(color)) % 997}">'
        f'<color rgba="{color}"/></material></visual><collision>{o}<geometry>{geo}</geometry></collision>'
    )


def _box(x, y, z, **kw) -> str:
    return _shape(f'<box size="{x:.6g} {y:.6g} {z:.6g}"/>', **kw)


def _cyl(r, h, **kw) -> str:
    return _shape(f'<cylinder radius="{r:.6g}" length="{h:.6g}"/>', **kw)


def urdf() -> str:
    a1, a2, c1, c2, c3, c4 = (OPW[k] for k in ("a1", "a2", "c1", "c2", "c3", "c4"))
    links = {
        "base_link": _cyl(0.20, 0.30, xyz=(0, 0, 0.15), color=GREY),
        "link_1": _cyl(0.17, 0.12, xyz=(0, 0, 0.36))
        + _box(0.30, 0.26, 0.16, xyz=(a1 / 2 + 0.02, 0, c1 - 0.02)),
        "link_2": _box(0.16, 0.14, c2 + 0.12, xyz=(0, 0, c2 / 2)),
        "link_3": _box(0.20, 0.16, 0.20, xyz=(0, 0, 0))
        + _cyl(0.075, c3 - 0.10, xyz=(a2, 0, (c3 - 0.10) / 2 + 0.02)),
        "link_4": _cyl(0.065, 0.12, xyz=(0, 0, -0.14)),
        "link_5": _cyl(0.05, 0.09, rpy=(math.pi / 2, 0, 0)),
        "link_6": _cyl(0.04, c4 * 0.6, xyz=(0, 0, c4 - c4 * 0.3), color=GREY),
        "tool0": "",
    }
    origins = [(0, 0, 0), (a1, OPW["b"], c1), (0, 0, c2), (a2, 0, c3), (0, 0, 0), (0, 0, 0)]
    out = [f'<robot name="{NAME}">']
    for name, body in links.items():
        inertial = (
            '<inertial><mass value="1"/><inertia ixx="0.01" iyy="0.01" izz="0.01" ixy="0" ixz="0" iyz="0"/>'
            "</inertial>"
            if name != "tool0"
            else ""
        )
        out.append(f'  <link name="{name}">{body}{inertial}</link>')
    names = list(links)
    for i in range(6):
        ax = AXES[i]
        rot = [0.0, 0.0, 0.0]
        rot[2 if ax == "z" else 1] = -OFFSETS[i]
        axis = {"z": (0, 0, SIGNS[i]), "y": (0, SIGNS[i], 0)}[ax]
        lo, hi = (math.radians(v) for v in LIMITS_DEG[i])
        out.append(
            f'  <joint name="joint_{i + 1}" type="revolute"><parent link="{names[i]}"/>'
            f'<child link="{names[i + 1]}"/><origin xyz="{" ".join(map(str, origins[i]))}" '
            f'rpy="{" ".join(f"{v:.9g}" for v in rot)}"/><axis xyz="{" ".join(map(str, axis))}"/>'
            f'<limit lower="{lo:.9g}" upper="{hi:.9g}" effort="1000" velocity="3"/></joint>'
        )
    out.append(
        f'  <joint name="flange" type="fixed"><parent link="link_6"/><child link="tool0"/>'
        f'<origin xyz="0 0 {c4}" rpy="0 0 0"/></joint>'
    )
    out.append("</robot>")
    return "\n".join(out) + "\n"


def spec() -> str:
    off = ", ".join(f"{v:.9g}" for v in OFFSETS)
    return f"""# A MADE-UP example arm (not a real product), generated by scripts/make_generic_robot.py.
# Copy this folder as a template when adding a real industrial arm: replace the URDF and
# meshes, set the OPW parameters from the manufacturer's data (or ROS-Industrial's
# opw_kinematics parameter file), then run scripts/check_robot.py {NAME}.
name: {NAME}
urdf: {NAME}.urdf
base_link: base_link
flange_link: tool0
ik: opw
reach_m: {OPW["a1"] + math.hypot(OPW["c2"] + math.hypot(OPW["a2"], OPW["c3"]), 0) + OPW["c4"]:.3f}
frame_convention: matrix
home_deg: [0, -90, 90, 0, 45, 0]

opw:
  a1: {OPW["a1"]}
  a2: {OPW["a2"]}
  b: {OPW["b"]}
  c1: {OPW["c1"]}
  c2: {OPW["c2"]}
  c3: {OPW["c3"]}
  c4: {OPW["c4"]}
  offsets: [{off}]
  sign_corrections: [{", ".join(map(str, SIGNS))}]
"""


def main() -> None:
    folder = REPO / "assets" / "robots" / NAME
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{NAME}.urdf").write_text(urdf(), encoding="utf-8")
    (folder / "spec.yaml").write_text(spec(), encoding="utf-8")
    print(f"wrote {folder}")


if __name__ == "__main__":
    main()
